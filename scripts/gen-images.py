"""Regenerates src/data/images.gen.ts: intrinsic size + tiny blur placeholder for every JPG in public/images.
Run after adding or replacing photos:  python scripts/gen-images.py"""
import base64, io, json, pathlib
from PIL import Image

root = pathlib.Path(__file__).resolve().parent.parent
out = {}
for p in sorted((root / "public/images").rglob("*.jpg")):
    key = p.relative_to(root / "public/images").as_posix()[:-4]
    im = Image.open(p).convert("RGB")
    t = im.copy(); t.thumbnail((12, 12)); b = io.BytesIO(); t.save(b, "WEBP", quality=40)
    out[key] = [im.width, im.height, "data:image/webp;base64," + base64.b64encode(b.getvalue()).decode()]
body = ",\n".join(f'  "{k}": [{w}, {h}, "{blur}"]' for k, (w, h, blur) in out.items())
(root / "src/data/images.gen.ts").write_text(
    "// Generated by scripts/gen-images.py. Do not edit by hand.\n"
    "export const IMAGE_META = {\n" + body + ",\n} as const satisfies Record<string, readonly [number, number, string]>;\n",
    encoding="utf-8",
)
print(len(out), "images")
